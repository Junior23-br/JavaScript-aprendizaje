//var, puede variar sus valores,
//  NO USARLA PARA DECLARAR VARIABLES
var helloWorld = "Hola"
console.log(helloWorld)
helloWorld = "Hola de nuevo"
console.log(helloWorld)

//let, valores cambiables
let helloworld2 = "Hola 2"
console.log(helloworld2)
helloworld2 = "Hola de nuevo 2"
console.log(helloworld2)

//const, Valores fijos
const helloWorld3 = "Hola 3"
console.log(helloWorld3)

//No se puede modificar su valor porque es constante
